import type { Nature, Skill, TraitId } from "./types";

/**
 * v17 technique catalogue — 350 standard-ninja development nodes.
 *
 * Every recruitable shinobi rolls a personal 10-tier development tree from
 * this pool (plus the retained trait/nature-gated identity nodes). Each node
 * belongs to a mechanic family so tree generation can offer genuinely
 * different choices per tier instead of three variations of "+X% ATK":
 *
 *   stat   — flat multipliers (the classic development nodes)
 *   cond   — conditional power (opening round, low HP, vs burning foes, ...)
 *   proc   — triggered statuses on strikes and crits
 *   ramp   — stacking power over rounds or on a single focused target
 *   risk   — oversized bonuses with a real drawback
 *   once   — once-per-battle powers (death-defy, unleashed strike)
 *   aura   — team synergies keyed to allies and natures
 *   support / econ — healing, protection, chakra economy
 *   village — mission-board effects
 *   signature — active combat techniques for the Techniques submenu
 *
 * Combat resolution for these fields lives in game/perks.ts (aggregation) and
 * game/battle.ts (triggers). This file is pure data.
 */

export type TechniqueFamily =
  | "stat" | "cond" | "proc" | "ramp" | "risk" | "once"
  | "aura" | "support" | "econ" | "village" | "signature";

export type ProcStatus = "burn" | "poison" | "bleed" | "shred" | "slow" | "stun";

export interface TechniqueProc {
  status: ProcStatus;
  chance: number;
  rounds: number;
  value?: number;
}

export interface TechniqueTech {
  name: string;
  power: number;
  stat: Skill;
  hits: number;
  note: string;
  /** flat damage multiplier applied to this technique only */
  atk?: number;
  /** hits every foe instead of one target */
  aoe?: boolean;
  /** auto-targets the lowest-HP foe */
  weakest?: boolean;
  /** instantly defeats targets left below this HP fraction */
  executeBelow?: number;
  /** ignores Guard damage reduction */
  pierceGuard?: boolean;
  /** stuns the target for N rounds after the strike */
  stunRounds?: number;
  /** applies a status on hit */
  status?: ProcStatus;
  statusRounds?: number;
  /** restores this fraction of max HP after use */
  selfHealPct?: number;
  /** drains this fraction of the target's max chakra */
  cpDrainPct?: number;
  /** healing technique: restores allies instead of damaging foes */
  heal?: boolean;
}

/**
 * Full effect vocabulary for technique nodes. Superset of the original Perk fx
 * fields (atk/def/hp/cp/crit/... plus `special`) so perks.ts can adopt it as
 * the canonical fx type for legacy and new nodes alike.
 *
 * Conditional multipliers stack multiplicatively. Threshold pairs
 * (`lowHpAtk` + `lowHpAtkBelow`, `vsLowHpAtk` + `vsLowHpBelow`, `lowHpDef` +
 * `lowHpDefBelow`) keep the strongest bonus when several nodes fire.
 */
export interface TechniqueFx {
  // classic stat development
  atk?: number;
  def?: number;
  hp?: number;
  cp?: number;
  crit?: number;
  critMult?: number;
  dodge?: number;
  lifesteal?: number;
  counter?: number;
  regen?: number;
  firstStrike?: boolean;
  special?: boolean;
  jutsu?: number;

  // triggered statuses (basic attacks / crits)
  proc?: TechniqueProc;
  critProc?: TechniqueProc;

  // kill spoils and chakra economy
  killHealPct?: number;
  killCpPct?: number;
  cpDrainPct?: number;
  upkeepCp?: number;
  upkeepHpPct?: number;

  // support
  healAmp?: number;
  guardAmp?: number;

  // conditional attack power
  firstRoundAtk?: number;
  firstBloodAtk?: number;
  lowHpAtk?: number;
  lowHpAtkBelow?: number;
  vsLowHpAtk?: number;
  vsLowHpBelow?: number;
  vsBurnAtk?: number;
  vsPoisonAtk?: number;
  vsBleedAtk?: number;
  vsStunnedAtk?: number;
  vsShreddedAtk?: number;
  outnumberedAtk?: number;
  allyHurtAtk?: number;

  // conditional defence
  lowHpDef?: number;
  lowHpDefBelow?: number;
  outnumberedDef?: number;
  lastStandDef?: number;

  // stacking growth
  rampAtkPerRound?: number;
  rampAtkMax?: number;
  rampDefPerRound?: number;
  rampDefMax?: number;
  rampCritPerRound?: number;
  rampCritMax?: number;
  focusAtkPerHit?: number;
  focusAtkMax?: number;

  // once per battle
  deathDefyPct?: number;
  unleashMult?: number;

  // team auras (applied at battle start)
  auraAllyAtk?: number;
  auraAllyDef?: number;
  auraAllyCrit?: number;
  auraAllyDodge?: number;
  auraAllyRegen?: number;
  auraSameNatureAtk?: number;
}

